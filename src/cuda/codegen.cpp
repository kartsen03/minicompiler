// The exact bit pattern, so the kernel uses the same float as the IR (this
// also covers infinities and NaN), with the decimal value as a comment.
std::string float_literal(float v) {
	std::uint32_t bits;
	std::memcpy(&bits, &v, sizeof bits);
	char buf[80];
	std::snprintf(buf, sizeof buf, "__uint_as_float(0x%08xu);  // %.9g", static_cast<unsigned>(bits),
	              static_cast<double>(v));
	return buf;
}

std::string op_expr(OpKind op, const std::string& a, const std::string& b) {
	switch (op) {
		case OpKind::Neg: return "-" + a;
		case OpKind::Exp: return "expf(" + a + ")";
		case OpKind::Log: return "logf(" + a + ")";
		case OpKind::Sqrt: return "sqrtf(" + a + ")";
		case OpKind::Relu: return "fmaxf(" + a + ", 0.0f)";
		case OpKind::Sigmoid: return "1.0f / (1.0f + expf(-" + a + "))";
		case OpKind::Tanh: return "tanhf(" + a + ")";
		case OpKind::Add: return a + " + " + b;
		case OpKind::Sub: return a + " - " + b;
		case OpKind::Mul: return a + " * " + b;
		case OpKind::Div: return a + " / " + b;
		default: return "/* unsupported op */ 0.0f";
	}
}

// How a kernel reads one input, given its shape and the output's shape.
struct Access {
	enum class Kind {
		Contiguous,  // the output's layout: element i
		Scalar,      // one value, loaded once before the loop
		Periodic,    // a suffix of the output's shape (e.g. a bias row): element i % period
		General,     // anything else: index math with constant divisors
	};
	Kind kind = Kind::Contiguous;
	std::size_t period = 0;
	std::string index;  // General: index expression in terms of i
};

Access classify(const Shape& in, const Shape& out) {
	const std::size_t n_in = num_elements(in);
	if (n_in == 1) return {Access::Kind::Scalar, 0, ""};
	if (n_in == num_elements(out)) return {Access::Kind::Contiguous, 0, ""};
	std::size_t lead = 0;
	while (lead < in.size() && in[lead] == 1) ++lead;
	const std::size_t rest = in.size() - lead;
	if (std::equal(in.begin() + static_cast<std::ptrdiff_t>(lead), in.end(), out.end() - static_cast<std::ptrdiff_t>(rest))) {
		return {Access::Kind::Periodic, n_in, ""};
	}

	// Sum over output dims of coord_d * stride_d, coord_d = (i / out_stride_d) % out_dim_d.
	const std::vector<std::int64_t> strides = broadcast_strides(in, out);
	std::vector<std::size_t> out_strides(out.size());
	std::size_t s = 1;
	for (std::size_t d=out.size(); d-- > 0;) {
		out_strides[d] = s;
		s *= static_cast<std::size_t>(out[d]);
	}
	std::string expr;
	for (std::size_t d=0; d<out.size(); ++d) {
		if (strides[d] == 0) continue;
		std::string coord = "i";
		if (out_strides[d] != 1) coord = "(i / " + std::to_string(out_strides[d]) + "u)";
		if (d > 0) coord = "(" + coord + " % " + std::to_string(out[d]) + "u)";  // the outermost coordinate never wraps
		const std::string term = strides[d] == 1 ? coord : coord + " * " + std::to_string(strides[d]) + "u";
		expr += (expr.empty() ? "" : " + ") + term;
	}
	return {Access::Kind::General, 0, expr};
}

